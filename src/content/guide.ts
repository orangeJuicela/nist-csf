export function functionGuide(id: string): FunctionGuide {
  const guide = functions[id];
  if (!guide) throw new Error(`missing function guide ${id}`);
  return guide;
}

export function categoryGuide(id: string): CategoryGuide {
  const guide = categories[id];
  if (!guide) throw new Error(`missing category guide ${id}`);
  return guide;
}
